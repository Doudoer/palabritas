export function getCurrentDayTheme(dayOffset = 0): DayThemeInfo {
  const now = new Date();
  const day = (now.getDay() + dayOffset + 7) % 7;
  return WEEKLY_DAY_THEMES[day] || WEEKLY_DAY_THEMES[1];
}

